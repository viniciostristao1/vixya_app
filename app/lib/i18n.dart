String tr(String key, [Map<String, String> params = const {}]) {
  final code = langCtrl.current.value.code;
  var s = _strings[code]?[key] ?? _strings['pt']![key] ?? key;
  params.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}
